def export_datasets_to_csv():
    """Exports datasets to data/ CSV files for inspection, download, or external tooling."""
    DATA_DIR.mkdir(exist_ok=True, parents=True)

    platforms_df = pd.DataFrame(KNOWN_OFFSHORE_PLATFORMS)
    platforms_file = DATA_DIR / "real_offshore_platforms.csv"
    platforms_df.to_csv(platforms_file, index=False)

    seeps_records = []
    for s in KNOWN_NATURAL_SEEPS:
        seeps_records.append({
            "seep_name": s["name"],
            "region": s["region"],
            "lease_block_or_area": s.get("lease_block", ""),
            "latitude": s["lat"],
            "longitude": s["lon"],
            "water_depth_m": s["depth_m"],
            "formation_type": s.get("formation", "Subsea fault"),
            "flux_bbl_day": s.get("flux_bbl_day", 20.0),
            "description": s["desc"],
            "source": s.get("source", "NOAA / BOEM"),
        })
    seeps_df = pd.DataFrame(seeps_records)
    seeps_file = DATA_DIR / "real_offshore_seeps.csv"
    seeps_df.to_csv(seeps_file, index=False)

    return str(seeps_file), str(platforms_file)

# Export automatically on import
export_datasets_to_csv()